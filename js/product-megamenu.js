const sidebar = document.getElementById("categorySidebar");
const rightContent = document.getElementById("dropdownRight");

let index = 0;

// ================= CREATE SIDEBAR =================
Object.keys(productsMegaMenu).forEach((category, i) => {
    const card = document.createElement("div");
    card.className = `sidebar-card ${i === 0 ? "active" : ""}`;
    card.dataset.target = `content-${i}`;

    card.innerHTML = `
    <h3>${category}</h3>
    <p>${productsMegaMenu[category].desc}</p>
  `;

    sidebar.appendChild(card);
});

// ================= CREATE PRODUCT CONTENT =================
Object.entries(productsMegaMenu).forEach(([category, data], i) => {
    const content = document.createElement("div");
    content.className = `dropdown-content one-content swiper ${i === 0 ? "active" : ""}`;
    content.id = `content-${i}`;

    const wrapper = document.createElement("div");
    wrapper.className = "swiper-wrapper";

    data.products.forEach(product => {
        wrapper.innerHTML += `
            <div class="swiper-slide">
                <a href="./product-details.html?id=${product.id}" class="content-card">
                    <img src="${product.img}" alt="${product.name}">
                    <h3 class="title">${product.name}</h3>
                    <p class="description">${product.desc}</p>
                </a>
            </div>
        `;
    });

    content.appendChild(wrapper);

    // --- VIEW MORE BUTTON ADDED HERE ---
    const categorySlug = category.toLowerCase().replace(/ /g, "-");

    const viewMoreBtn = document.createElement("div");
    viewMoreBtn.className = "view-more-container";
    viewMoreBtn.innerHTML = `
        <a href="./product.html?series=${encodeURIComponent(category)}" class="view-more-btn">
    View All Products <i class="fa-solid fa-arrow-right"></i>
</a>
    `;
    content.appendChild(viewMoreBtn);

    // Swiper buttons
    content.innerHTML += `
        <div class="swiper-button-prev custom-prev">
            <i class="fa-solid fa-chevron-left"></i>
        </div>
        <div class="swiper-button-next custom-next">
            <i class="fa-solid fa-chevron-right"></i>
        </div>
    `;

    rightContent.appendChild(content);
});
// ================= SIDEBAR CLICK HANDLER =================
document.querySelectorAll(".sidebar-card").forEach((card, i) => {
    card.addEventListener("mouseenter", () => {
        document.querySelectorAll(".sidebar-card").forEach(c => c.classList.remove("active"));
        document.querySelectorAll(".dropdown-content").forEach(c => c.classList.remove("active"));

        card.classList.add("active");
        document.getElementById(`content-${i}`).classList.add("active");
    });
});
